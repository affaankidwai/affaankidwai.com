// --- Photo helpers ---

export function photoSrc(photo) {
  return `/gallery/${photo.id}.jpg`;
}

export function photoLabel(photo, index) {
  if (photo.title) return photo.title;
  return `Frame ${String(index + 1).padStart(2, "0")}`;
}

export function getPhotoBySlug(slug) {
  return photos.find((p) => p.slug === slug);
}

export function getPhotoNeighbours(slug) {
  const i = photos.findIndex((p) => p.slug === slug);
  if (i < 0) return { prev: null, next: null };
  const prev = i > 0 ? photos[i - 1] : photos[photos.length - 1];
  const next = i < photos.length - 1 ? photos[i + 1] : photos[0];
  return { prev, next };
}

export function formatPhotoDate(value) {
  if (!value) return "";
  const date = new Date(value);
  if (Number.isNaN(date.getTime())) return value;
  return date.toLocaleDateString("en-GB", {
    day: "numeric",
    month: "long",
    year: "numeric",
  });
}

