// Categories present in the gallery, in display order.
const categoryOrder = ["Tigers", "Birds", "Wildlife"];
export const photoCategories = Array.from(
  new Set(photos.map((p) => p.category).filter(Boolean)),
).sort((a, b) => {
  const ia = categoryOrder.indexOf(a);
  const ib = categoryOrder.indexOf(b);
  if (ia === -1 && ib === -1) return a.localeCompare(b);
  if (ia === -1) return 1;
  if (ib === -1) return -1;
  return ia - ib;
});
